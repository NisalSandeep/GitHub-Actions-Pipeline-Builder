import { load } from 'js-yaml';

export interface ValidationError {
  line: number;
  column?: number;
  message: string;
  rule: string;
  severity: 'error' | 'warning';
}

export interface ValidationWarning {
  line?: number;
  message: string;
  suggestion?: string;
}

export interface ValidationStats {
  lines: number;
  jobsCount: number;
  stepsCount: number;
  triggers: string[];
  secrets: string[];
  runners: string[];
}

export interface ValidationResult {
  isValid: boolean;
  errors: ValidationError[];
  warnings: ValidationWarning[];
  stats: ValidationStats;
  parsed: Record<string, any> | null;
}

export interface SuggestionItem {
  prefix: string;
  label: string;
  snippet: string;
  description: string;
  category: 'directive' | 'runner' | 'action' | 'trigger' | 'expression' | 'strategy';
  iconName?: string;
}

